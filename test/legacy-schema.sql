CREATE TABLE IF NOT EXISTS prs (
  id INTEGER PRIMARY KEY,
  url TEXT NOT NULL UNIQUE,
  repo TEXT NOT NULL,
  number INTEGER NOT NULL,
  title TEXT NOT NULL,
  author TEXT NOT NULL,
  role TEXT NOT NULL,
  head_ref TEXT NOT NULL,
  head_sha TEXT NOT NULL,
  base_ref TEXT NOT NULL,
  is_cross_repo INTEGER NOT NULL DEFAULT 0,
  is_draft INTEGER NOT NULL DEFAULT 0,
  state TEXT NOT NULL DEFAULT 'open',
  gh_updated_at TEXT NOT NULL DEFAULT '',
  check_state TEXT,
  summary TEXT,
  worktree TEXT,
  session_id TEXT,
  paused INTEGER NOT NULL DEFAULT 0,
  blocked TEXT,
  agent_running INTEGER NOT NULL DEFAULT 0,
  dirty_by_agent INTEGER NOT NULL DEFAULT 0,
  interrupted INTEGER NOT NULL DEFAULT 0,
  batch_head_sha TEXT,
  last_event_at TEXT,
  ci_attempts INTEGER NOT NULL DEFAULT 0,
  in_review_search INTEGER NOT NULL DEFAULT 0,
  review_state TEXT NOT NULL DEFAULT 'none',
  review_verdict TEXT,
  review_body TEXT,
  review_draft_sha TEXT,
  reviewed_sha TEXT,
  reviewed_at TEXT,
  review_out_of_date INTEGER NOT NULL DEFAULT 0,
  review_threads TEXT,
  ignored INTEGER NOT NULL DEFAULT 0,
  ready INTEGER NOT NULL DEFAULT 0,
  kept TEXT,
  self_review_sha TEXT,
  self_review_state TEXT,
  self_review_result TEXT,
  self_review_round INTEGER NOT NULL DEFAULT 0,
  push_after TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE TABLE IF NOT EXISTS comments (
  id INTEGER PRIMARY KEY,
  pr_id INTEGER NOT NULL REFERENCES prs(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  gh_key TEXT NOT NULL,
  thread_id TEXT,
  reply_to_db_id INTEGER,
  last_seen_gh_id TEXT,
  author TEXT,
  body TEXT NOT NULL,
  path TEXT,
  line INTEGER,
  outdated INTEGER NOT NULL DEFAULT 0,
  diff_hunk TEXT,
  url TEXT,
  state TEXT NOT NULL DEFAULT 'new',
  proposal TEXT,
  reply_draft TEXT,
  reply_edited INTEGER NOT NULL DEFAULT 0,
  skip_reason TEXT,
  decision TEXT,
  auto INTEGER NOT NULL DEFAULT 0,
  risk TEXT,
  confidence TEXT,
  reason TEXT,
  by_agent INTEGER NOT NULL DEFAULT 0,
  note TEXT,
  task TEXT,
  task_source TEXT,
  clarify INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  UNIQUE (pr_id, gh_key)
);
CREATE TABLE IF NOT EXISTS questions (
  id INTEGER PRIMARY KEY,
  pr_id INTEGER NOT NULL REFERENCES prs(id) ON DELETE CASCADE,
  comment_id INTEGER,
  question TEXT NOT NULL,
  options TEXT,
  answer TEXT,
  state TEXT NOT NULL DEFAULT 'open',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE TABLE IF NOT EXISTS findings (
  id INTEGER PRIMARY KEY,
  pr_id INTEGER NOT NULL REFERENCES prs(id) ON DELETE CASCADE,
  kind TEXT NOT NULL DEFAULT 'finding',
  path TEXT,
  line INTEGER,
  thread_id TEXT,
  reply_to_db_id INTEGER,
  in_diff INTEGER NOT NULL DEFAULT 1,
  resolve INTEGER NOT NULL DEFAULT 0,
  body TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'draft',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE TABLE IF NOT EXISTS work_items (
  id INTEGER PRIMARY KEY,
  pr_id INTEGER NOT NULL REFERENCES prs(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  payload TEXT,
  state TEXT NOT NULL DEFAULT 'queued',
  error TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  started_at TEXT,
  finished_at TEXT
);
CREATE TABLE IF NOT EXISTS kv (
  key TEXT PRIMARY KEY,
  value TEXT
);
